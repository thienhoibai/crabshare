function parseStep(s) {
  let m;
  if ((m = s.match(/^(\w+)(->>|-->|->)(\w+):\s*(.*)$/))) return { kind: 'msg', from: m[1], to: m[3], arrow: m[2], text: m[4] };
  if ((m = s.match(/^(alt|opt|loop|par)\s*(.*)$/))) return { kind: 'open', op: m[1], guard: m[2] };
  if ((m = s.match(/^else\s*(.*)$/))) return { kind: 'else', guard: m[1] };
  if (s === 'end') return { kind: 'close' };
  if ((m = s.match(/^note:\s*(.*)$/))) return { kind: 'note', text: m[1] };
  throw new Error('bad step: ' + s);
}

function drawSequence(f, q) {
  const d = f.page(q.page);
  d.caption(q.fig, `Sequence Diagram – ${q.title}`, META);
  const ids = q.lifelines.map(l => l[0]);
  const colW = 200, x0 = 40, top = 90, headH = 40;
  const xc = (id) => x0 + ids.indexOf(id) * colW + 80; // tâm lifeline
  const steps = q.steps.map(parseStep);
  const rowH = 30;
  const total = steps.reduce((a, s) => a + (s.kind === 'msg' ? (s.from === s.to ? rowH + 14 : rowH) : s.kind === 'note' ? rowH + 8 : rowH), 0) + 80;
  // lifelines
  q.lifelines.forEach(([id, name, kind], i) => {
    const style = kind === 'actor' ? S.lifelineActor : S.lifeline + (kind === 'db' ? 'fillColor=#f1f5f9;' : kind === 'port' ? 'fillColor=#fef3c7;' : kind === 'ext' ? 'fillColor=#fee2e2;' : kind === 'job' ? 'fillColor=#ede9fe;' : kind === 'ui' ? 'fillColor=#ecfdf5;' : kind === 'ctrl' ? 'fillColor=#e0f2fe;' : '');
    const label = kind === 'actor' ? name : `${kind === 'port' ? '«interface»<br>' : kind === 'ext' ? '«external system»<br>' : kind === 'job' ? '«background job»<br>' : kind === 'ui' ? '«boundary»<br>' : kind === 'ctrl' ? '«controller»<br>' : kind === 'db' ? '«persistence»<br>' : '«service»<br>'}<b>:${name}</b>`;
    d.vertex(label, style, x0 + i * colW, top, 160, total, { key: 'll_' + id, raw: true });
  });
  // messages & fragments: pass 1 compute y
  let y = top + headH + 24;
  const frames = []; const stack = [];
  const items = [];
  for (const s of steps) {
    if (s.kind === 'open') { stack.push({ op: s.op, guard: s.guard, y0: y, seps: [] }); y += rowH; continue; }
    if (s.kind === 'else') { const fr = stack[stack.length - 1]; fr.seps.push({ y, guard: s.guard }); y += rowH; continue; }
    if (s.kind === 'close') { const fr = stack.pop(); fr.y1 = y; frames.push(fr); y += 10; continue; }
    if (s.kind === 'note') { items.push({ ...s, y }); y += rowH + 8; continue; }
    items.push({ ...s, y });
    y += s.from === s.to ? rowH + 14 : rowH;
  }
  const xl = x0 + 10, xr = x0 + ids.length * colW - 30;
  for (const fr of frames) {
    const depth = frames.filter(o => o.y0 < fr.y0 && o.y1 > fr.y1).length;
    d.vertex(`<b>${fr.op}</b>`, S.frame + 'fillColor=none;', xl + depth * 8, fr.y0 - 6, xr - xl - depth * 16, fr.y1 - fr.y0 + 6, { raw: true });
    d.text(`<font style="font-size:10px">${fr.guard}</font>`, xl + depth * 8 + 60, fr.y0 - 6, 400, 22, 'verticalAlign=middle;');
    for (const sp of fr.seps) {
      d.freeEdge(xl + depth * 8, sp.y + 10, xr - depth * 8, sp.y + 10, 'dashed=1;endArrow=none;strokeColor=#1e293b;html=1;');
      d.text(`<font style="font-size:10px">${sp.guard}</font>`, xl + depth * 8 + 6, sp.y + 8, 400, 20, 'verticalAlign=middle;');
    }
  }
  for (const it of items) {
    if (it.kind === 'note') { d.vertex(it.text, S.note + 'fontSize=9;', xl + 40, it.y, xr - xl - 80, rowH + 4, { raw: true }); continue; }
    const x1 = xc(it.from), x2 = xc(it.to);
    const style = it.arrow === '-->' ? S.msgReturn : it.arrow === '->>' ? S.msgAsync : S.msgSync;
    if (it.from === it.to) {
      d.freeEdge(x1 + 5, it.y, x1 + 5, it.y + 24, style + 'edgeStyle=orthogonalEdgeStyle;', { label: it.text, points: [[x1 + 60, it.y], [x1 + 60, it.y + 24]], raw: true });
      d.vertex('', S.activation, x1 - 5, it.y - 2, 10, 30);
      continue;
    }
    if (it.arrow !== '-->') d.vertex('', S.activation, x2 - 5, it.y - 4, 10, 22);
    d.freeEdge(x1, it.y, x2, it.y, style + 'labelBackgroundColor=#ffffff;', { label: `<font style="font-size:9px">${it.text}</font>`, raw: true });
  }
  d.vertex('<b>Legend</b> — solid filled arrow: synchronous call · open arrow: asynchronous · dashed: reply/result · «interface» lifelines are Infrastructure ports (Fake adapters in Development) · ProblemDetails code on error replies.', S.legend, x0, top + total + 20, Math.min(1100, ids.length * colW), 40, { raw: true });
}

function run(out) {
  const f = new DrawioFile();
  for (const q of SEQS) drawSequence(f, q);
  f.write(path.join(out, 'CrabShare_Sequence_Diagrams.drawio'));
  console.log('Sequence diagrams done:', SEQS.length);
}
